    private static String format(String input) {
        StringBuilder sb = new StringBuilder();

        String[] lines = input.split("\\R"); // handles \n, \r\n

        for (String line : lines) {
            line = line.trim();
            if (!line.isEmpty()) {
                sb.append("'")
                        .append(line)
                        .append("',");
            }
        }

        // remove last comma
        if (sb.length() > 0) {
            sb.setLength(sb.length() - 1);
        }

        return sb.toString();
    }

